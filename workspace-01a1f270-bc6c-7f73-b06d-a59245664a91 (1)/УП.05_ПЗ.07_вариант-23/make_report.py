def p(text="", bold=False, italic=False, size=12, align=None, space_after=4,
      color=None, first_line=0, left=0):
    par = doc.add_paragraph()
    run = par.add_run(text)
    run.bold = bold
    run.italic = italic
    run.font.size = Pt(size)
    run.font.name = "Times New Roman"
    if color:
        run.font.color.rgb = RGBColor(*color)
    if align == "c":
        par.alignment = WD_ALIGN_PARAGRAPH.CENTER
    elif align == "r":
        par.alignment = WD_ALIGN_PARAGRAPH.RIGHT
    elif align == "j":
        par.alignment = WD_ALIGN_PARAGRAPH.JUSTIFY
    par.paragraph_format.space_after = Pt(space_after)
    if first_line:
        par.paragraph_format.first_line_indent = Cm(first_line)
    if left:
        par.paragraph_format.left_indent = Cm(left)
    return par


def h(text, level=1):
    sizes = {1: 14, 2: 13, 3: 12}
    par = doc.add_paragraph()
    run = par.add_run(text)
    run.bold = True
    run.font.size = Pt(sizes.get(level, 12))
    run.font.name = "Times New Roman"
    par.paragraph_format.space_before = Pt(12 if level == 1 else 8)
    par.paragraph_format.space_after = Pt(6)
    par.paragraph_format.keep_with_next = True
    return par


def bullet(text, size=12):
    par = doc.add_paragraph(style="List Bullet")
    run = par.add_run(text)
    run.font.size = Pt(size)
    run.font.name = "Times New Roman"
    par.paragraph_format.space_after = Pt(2)
    return par


def code_block(lines, size=9):
    par = doc.add_paragraph()
    shd = OxmlElement("w:shd")
    shd.set(qn("w:fill"), "F2F2F2")
    par._p.get_or_add_pPr().append(shd)
    par.paragraph_format.left_indent = Cm(0.3)
    par.paragraph_format.space_after = Pt(6)
    for i, ln in enumerate(lines):
        run = par.add_run(ln)
        run.font.name = "Consolas"
        run.element.rPr.rFonts.set(qn("w:eastAsia"), "Consolas")
        run.font.size = Pt(size)
        if i < len(lines) - 1:
            run.add_break()
    return par


def set_cell(cell, text, bold=False, size=10, align=None, fill=None):
    cell.text = ""
    par = cell.paragraphs[0]
    run = par.add_run(text)
    run.bold = bold
    run.font.size = Pt(size)
    run.font.name = "Times New Roman"
    if align == "c":
        par.alignment = WD_ALIGN_PARAGRAPH.CENTER
    par.paragraph_format.space_after = Pt(1)
    par.paragraph_format.line_spacing = 1.0
    if fill:
        shd = OxmlElement("w:shd")
        shd.set(qn("w:fill"), fill)
        cell._tc.get_or_add_tcPr().append(shd)


def table(headers, rows, widths=None, size=10, header_fill="D9E2F3"):
    t = doc.add_table(rows=1, cols=len(headers))
    t.style = "Table Grid"
    t.alignment = WD_TABLE_ALIGNMENT.CENTER
    for i, hd in enumerate(headers):
        set_cell(t.rows[0].cells[i], hd, bold=True, size=size, align="c", fill=header_fill)
    for row in rows:
        cells = t.add_row().cells
        for i, v in enumerate(row):
            set_cell(cells[i], str(v), size=size, align="c" if i > 0 else None)
    if widths:
        for r in t.rows:
            for i, w in enumerate(widths):
                r.cells[i].width = Cm(w)
    doc.add_paragraph().paragraph_format.space_after = Pt(2)
    return t


def shot_placeholder(caption, instruction):
    """Рамка-заглушка под скриншот."""
    t = doc.add_table(rows=1, cols=1)
    t.style = "Table Grid"
    cell = t.rows[0].cells[0]
    cell.text = ""
    par = cell.paragraphs[0]
    par.alignment = WD_ALIGN_PARAGRAPH.CENTER
    run = par.add_run("\n[ МЕСТО ДЛЯ СКРИНШОТА ]\n")
    run.bold = True
    run.font.size = Pt(11)
    run.font.name = "Times New Roman"
    par2 = cell.add_paragraph()
    par2.alignment = WD_ALIGN_PARAGRAPH.CENTER
    r2 = par2.add_run(instruction)
    r2.italic = True
    r2.font.size = Pt(9)
    r2.font.name = "Times New Roman"
    r2.font.color.rgb = RGBColor(0x80, 0x80, 0x80)
    p(caption, italic=True, size=10, align="c", space_after=8)


